"""Turn a sampled kit's drum samples (WAV) into a C table the firmware plays from flash: firmware/gen/<kit>_samples.h

  python3 tools/samples2c.py lm1 DIR        the LM-1      -> firmware/gen/lm1_samples.h
  python3 tools/samples2c.py minipops DIR   the MINI POPS -> firmware/gen/minipops_samples.h

Six samples a kit, in the kit's row order (KICK SNARE HAT OPEN, then what the CLAP and PERC rows play; their names on
the drum page come with them). Each is read (mono, 16 bit, 44.1 kHz), optionally brought up to full scale, its
near-silent tail trimmed (below -60 dB of its peak, with a 5 ms fade), and stored 8-bit mu-law (companded, like the
old machines' own 8-bit samples), with the 256-entry table that expands it back to 16 bit. Only the Python standard
library is used. Where each kit's sounds come from, and on what terms: LICENSING.md, assets/samples/."""
import sys
import wave
from pathlib import Path

KITS = {
    "lm1": {
        "prefix": "LM1",
        "spdx": "CC-Sampling-Plus-1.0 (the sounds; see LICENSING.md)",
        "about": ["rossf's \"Linn LM1 (LM-1) Drum Set\" (Freesound pack 4919, Sampling+ 1.0,",
                  " * https://freesound.org/people/rossf/packs/4919/): the LM-1 kit's samples"],
        "normalise": False,
        "samples": [("lm1-kick.wav", "KICK"), ("lm1-snare.wav", "SNARE"), ("lm1-hat-cl.wav", "HAT"),
                    ("lm1-hat-open.wav", "OPEN"), ("lm1-tom-lo.wav", "TOM L"), ("lm1-tom-hi.wav", "TOM H")],
    },
    "minipops": {
        "prefix": "MP",
        "spdx": "LicenseRef-Drumkito (the sounds: no licence stated; see assets/samples/MINIPOPS-SOURCE.txt)",
        "about": ["Drumkito's \"Korg Mini Pops Sample Pack\" (a Korg Mini Pops 120,",
                  " * https://www.drumkito.com/sample-packs/korg-mini-pops-sample-pack/): the MINI POPS kit's samples"],
        "normalise": True,
        "samples": [("bd2.wav", "KICK"), ("sd3.wav", "SNARE"), ("hihat1.wav", "HAT"), ("hihat2.wav", "OPEN"),
                    ("sd2.wav", "SNAP"), ("wood1.wav", "WOOD")],
    },
}
GEN = Path(__file__).resolve().parents[1] / "firmware" / "gen"
BIAS, CLIP = 0x84, 32635


def mulaw_enc(s):
    sign = 0x80 if s < 0 else 0
    s = min(abs(s), CLIP) + BIAS
    exp = 7
    while exp > 0 and not (s & (0x4000 >> (7 - exp))):
        exp -= 1
    mant = (s >> (exp + 3)) & 0x0F
    return ~(sign | (exp << 4) | mant) & 0xFF


def mulaw_dec(u):
    u = ~u & 0xFF
    sign, exp, mant = u & 0x80, (u >> 4) & 7, u & 0x0F
    s = ((mant << 3) + BIAS) << exp
    s -= BIAS
    return -s if sign else s


def read(path):
    with wave.open(str(path)) as w:
        if w.getnchannels() != 1 or w.getsampwidth() != 2 or w.getframerate() != 44100:
            raise SystemExit(f"{path.name}: want mono 16-bit 44.1 kHz")
        raw = w.readframes(w.getnframes())
    return [int.from_bytes(raw[i:i + 2], "little", signed=True) for i in range(0, len(raw), 2)]


def trim(x):
    pk = max(abs(v) for v in x) or 1
    end = len(x)
    while end > 1 and abs(x[end - 1]) < pk / 1000:   # -60 dB
        end -= 1
    x = x[:end]
    fade = min(220, len(x))                           # 5 ms
    for i in range(fade):
        x[len(x) - fade + i] = x[len(x) - fade + i] * (fade - 1 - i) // fade
    return x


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in KITS:
        raise SystemExit(__doc__)
    kit, d = KITS[sys.argv[1]], Path(sys.argv[2])
    px = kit["prefix"]
    out_path = GEN / f"{sys.argv[1]}_samples.h"
    out = [f"/* SPDX-License-Identifier: {kit['spdx']} */",
           f"/* generated by tools/samples2c.py from {kit['about'][0]}", f"{kit['about'][1]}, 8-bit mu-law at 44.1 kHz. Do not edit. */",
           "#pragma once", "#include <stdint.h>", "", "#ifndef MULAW_TABLE", "#define MULAW_TABLE",
           "static const int16_t MULAW[256] = {"]
    dec = [mulaw_dec(u) for u in range(256)]
    for i in range(0, 256, 16):
        out.append("    " + ", ".join(str(v) for v in dec[i:i + 16]) + ",")
    out[-1] = out[-1].rstrip(",") + "};"
    out.append("#endif")
    total = 0
    names, lens = [], []
    for k, (suffix, label) in enumerate(kit["samples"]):
        files = [p for p in d.iterdir() if p.name.lower().endswith(suffix) and not p.name.startswith("._")]
        if len(files) != 1:
            raise SystemExit(f"{suffix}: not found (or more than one) in {d}")
        x = read(files[0])
        if kit["normalise"]:                            # up to 31000 at its peak (the samples came at different levels)
            pk = max(abs(v) for v in x) or 1
            x = [v * 31000 // pk for v in x]
        x = trim(x)
        enc = [mulaw_enc(v) for v in x]
        total += len(enc)
        names.append(label)
        lens.append(len(enc))
        out.append("")
        out.append(f"static const uint8_t {px}_S{k}[{len(enc)}] = {{   /* {label}: {files[0].name}, {len(enc) / 44.1:.0f} ms */")
        for i in range(0, len(enc), 24):
            out.append("    " + ", ".join(str(v) for v in enc[i:i + 24]) + ",")
        out[-1] = out[-1].rstrip(",") + "};"
    out += ["", f"#define {px}_NSAMPLE 6u",
            f"static const uint8_t *const {px}_DATA[{px}_NSAMPLE] = {{" + ", ".join(f"{px}_S{k}" for k in range(6)) + "};",
            f"static const uint32_t {px}_LEN[{px}_NSAMPLE] = {{" + ", ".join(str(n) for n in lens) + "};",
            f"static const char *const {px}_ROW[{px}_NSAMPLE] = {{" + ", ".join(f'"{n}"' for n in names) + "};", ""]
    out_path.write_text("\n".join(out), encoding="utf-8")
    print(f"{out_path}: {total} bytes of samples ({total / 44100:.2f} s), " + ", ".join(f"{n} {l / 44.1:.0f} ms" for n, l in zip(names, lens)))


if __name__ == "__main__":
    main()
